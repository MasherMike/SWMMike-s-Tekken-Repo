"""
Collect Mike's Tekken 8 battles from the ewgf.gg API into data/battles.jsonl.

Runs every 6 hours from .github/workflows/collect-battles.yml.
The free API tier returns the last 50 battles (24h delayed); polling every
6 hours keeps every window well under 50 games, so nothing is missed.

PRIVACY: only the fields in ALLOWED_FIELDS are ever written - no names, IDs,
regions or Tekken Power, for Mike or for opponents. Every script that writes
battle data goes through save_rows(), which drops anything not on the list and
refuses to write a value that looks like a player ID.
  battle_at, mode, my_char, opp_char, opp_rank, result, rounds, stage_id, stage
  my_rating, opp_rating   (Wavu Wank skill ratings before the game, approved 2026-10-13)
"""

import csv
import gzip
import re
import json
import os
import sys
import urllib.error
import urllib.request

TEKKEN_ID = "4bN6AEeddYT6"          # Mike's Tekken ID (public, from his ewgf URL)
URL = f"https://api.ewgf.gg/external/battles/{TEKKEN_ID}"
BATTLES = "data/battles.jsonl"
STAGES = "data/stages.json"
PAGE_COPY = "data/battles.js"
CSV_COPY = "data/battles.csv"
CSV_FIELDS = ["battle_at", "mode", "my_char", "opp_char", "opp_rank", "result",
              "rounds", "stage_id", "stage"]

ALLOWED_FIELDS = ["battle_at", "mode", "my_char", "opp_char", "opp_rank", "result",
                  "rounds", "stage_id", "stage", "my_rating", "opp_rating"]
ID_LIKE = re.compile(r"^[1-9A-HJ-NP-Za-km-z]{12}$")   # Tekken/Polaris ID shape, e.g. 4bN6AEeddYT6

MODES = {"RANKED_BATTLE": "ranked", "QUICK_BATTLE": "quick",
         "PLAYER_BATTLE": "player", "GROUP_BATTLE": "group"}


def fetch():
    key = os.environ.get("EWGF_API_KEY")
    if not key:
        sys.exit("EWGF_API_KEY secret is missing.")
    req = urllib.request.Request(URL, headers={
        "Authorization": f"Bearer {key}", "Accept-Encoding": "gzip"})
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            raw = resp.read()
            if resp.headers.get("Content-Encoding") == "gzip":
                raw = gzip.decompress(raw)
            return json.loads(raw)
    except urllib.error.HTTPError as e:
        body = e.read()
        try:
            body = gzip.decompress(body)
        except OSError:
            pass
        sys.exit(f"API error {e.code}: {body.decode(errors='replace')[:500]}")


def slim(b, stage_names):
    """Reduce one raw battle to the 7 approved fields, from Mike's point of view."""
    me_first = b.get("p1_tekken_id") == TEKKEN_ID
    if not me_first and b.get("p2_tekken_id") != TEKKEN_ID:
        return None                                  # not Mike's battle; skip
    me, opp = ("p1", "p2") if me_first else ("p2", "p1")
    my_rounds, opp_rounds = b.get(f"{me}_rounds_won"), b.get(f"{opp}_rounds_won")
    won = b.get("winner") == (1 if me_first else 2)
    stage_id = b.get("stage_id")
    return {
        "battle_at": b.get("battle_at"),
        "mode": MODES.get(b.get("battle_type"), str(b.get("battle_type", "")).lower()),
        "my_char": b.get(f"{me}_char"),
        "opp_char": b.get(f"{opp}_char"),
        "opp_rank": b.get(f"{opp}_dan_rank"),
        "result": "W" if won else "L",
        "rounds": f"{my_rounds}-{opp_rounds}",
        "stage_id": stage_id,
        "stage": stage_names.get(str(stage_id)),     # None until the ID is confirmed
    }


def key(r):
    """Same battle seen in two pulls -> same key, so it's stored once."""
    return (r["battle_at"], r["my_char"], r["opp_char"], r["rounds"], r["stage_id"])


def clean(r):
    """Keep only approved fields. A text value shaped like a player ID is a bug
    somewhere upstream, so stop rather than write it."""
    out = {k: r.get(k) for k in ALLOWED_FIELDS if r.get(k) is not None or k in r}
    for k, v in out.items():
        if isinstance(v, str) and k not in ("battle_at",) and ID_LIKE.match(v):
            sys.exit(f"Refusing to save: field {k!r} looks like a player ID.")
    return out


def save_rows(rows):
    """The only way battle data reaches disk: jsonl + page copy + CSV."""
    rows = sorted((clean(r) for r in rows), key=lambda r: str(r["battle_at"]))
    os.makedirs("data", exist_ok=True)
    with open(BATTLES, "w") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    write_page_copy(rows)
    write_csv_copy(rows)
    return rows


def load_rows():
    if not os.path.exists(BATTLES):
        return []
    with open(BATTLES) as fh:
        return [json.loads(line) for line in fh if line.strip()]


def write_page_copy(rows):
    """data/battles.js - the same rows as a script index.html can load.
    A plain <script src> works on GitHub Pages AND when the page is opened as a
    local file, where browsers block fetch() of .jsonl files."""
    with open(PAGE_COPY, "w") as fh:
        fh.write("// Generated by scripts/collect_battles.py - do not edit by hand.\n")
        fh.write("window.BATTLES = ")
        json.dump(rows, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")


def write_csv_copy(rows):
    """data/battles.csv - same rows as a CSV, for Google Sheets' IMPORTDATA.
    Rounds are written as "3 to 1" so spreadsheets don't read "3-1" as a date."""
    with open(CSV_COPY, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=CSV_FIELDS, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({**r, "rounds": str(r.get("rounds", "")).replace("-", " to ")})


def main():
    with open(STAGES) as fh:
        stage_names = json.load(fh)["confirmed"]

    existing = load_rows()
    seen = {key(r) for r in existing}

    payload = fetch()
    raw = payload.get("data", [])
    new = []
    for b in raw:
        r = slim(b, stage_names)
        if r and key(r) not in seen:
            seen.add(key(r))
            new.append(r)

    # Back-fill stage names for older rows if an ID was confirmed since.
    for r in existing:
        if r.get("stage") is None:
            r["stage"] = stage_names.get(str(r.get("stage_id")))

    rows = save_rows(existing + new)

    unknown = sorted({r["stage_id"] for r in rows if r["stage"] is None})
    print(f"Pulled {len(raw)} battles, {len(new)} new, {len(rows)} total. "
          f"Requests left this hour: {payload.get('_metadata', {}).get('rate_limit_remaining')}.")
    if unknown:
        print(f"Unmapped stage IDs: {unknown}")


if __name__ == "__main__":
    main()
